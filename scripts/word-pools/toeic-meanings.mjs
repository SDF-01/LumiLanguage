export function glossFor(word) {
  const key = word.toLowerCase().trim();
  const hit = TOEIC_GLOSS[key];
  if (hit) {
    return {
      meaningEn: hit[0],
      explanationEn: `TOEIC workplace English: ${word}. ${hit[0]}.`,
      explanationJa: hit[1],
    };
  }

  // Lightweight pattern glosses when not in the curated map.
  if (key.endsWith("tion") || key.endsWith("sion")) {
    return {
      meaningEn: `business noun: ${word}`,
      explanationEn: `A common TOEIC noun. Practice: use "${word}" in a short office sentence.`,
      explanationJa: `TOEICでよく出る名詞です。「${word}」を短い仕事の文で使いましょう。`,
    };
  }
  if (key.endsWith("ment")) {
    return {
      meaningEn: `action or result: ${word}`,
      explanationEn: `Often names a process or result at work. Say it, then use it once aloud.`,
      explanationJa: `仕事のプロセスや結果を表すことが多い語です。声に出して使いましょう。`,
    };
  }
  if (key.includes(" ")) {
    return {
      meaningEn: `business phrase: ${word}`,
      explanationEn: `A multi-word workplace expression. Listen, then repeat the whole phrase.`,
      explanationJa: `複数語のビジネス表現です。まとめて聞いて繰り返しましょう。`,
    };
  }
  return {
    meaningEn: `workplace word: ${word}`,
    explanationEn: `High-frequency TOEIC vocabulary. Say "${word}", then use it in one short work sentence.`,
    explanationJa: `TOEIC頻出語です。「${word}」を声に出し、短い仕事の文で使いましょう。`,
  };
}
